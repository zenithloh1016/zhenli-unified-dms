/**
 * Private Register Book -> Master Listing enrichment.
 * Registers are parsed in the user's browser; no statutory names are bundled in public assets.
 * Only current directors, members and beneficial owners are transferred into the portfolio.
 * Historical register material stays in the original documents, not the Master Listing.
 */
import {unzipSync} from 'fflate';
import {openMasterListingWorkbook} from './master-listing-reader.js';
import {companyData,validateMasterListing} from './master-listing-data.js';

export const REGISTER_PARTICULARS_COLUMNS=['Current Directors','Current Members','Current Beneficial Owners'];
// These are *only* the additional statutory-detail headers generated by the earlier
// 42-column Register Book consolidation (plus the two-column legacy import).
// Do not delete any original Master Listing business, tax, bank or deadline fields.
const REDUNDANT_REGISTER_HEADERS=new Set([
 'directors & members','beneficial owners','director count','member count',
 'bo count','member shareholdings (register)','bo ownership type / criteria',
 'registered office','register last updated','current secretaries',
 'current managers','total shares allotted (historical)',
 'share classes allotted','allotment entries','transfer entries',
 'chargees (registered)','charge discharge details (register)',
 'register source / status'
]);
const normHeader=value=>String(value??'').trim().toLowerCase();
const MAX_ZIP=80*1024*1024;
const MAX_UNPACKED=120*1024*1024;
const MAX_BOOK=20*1024*1024;
const maxField=15000;

const clean=value=>String(value??'').trim().replace(/[ \t]+/g,' ');
const firstLine=value=>clean(value).split(/\r?\n/)[0].trim();
const companyKey=value=>firstLine(value).normalize('NFKC').toUpperCase().replace(/[^A-Z0-9]+/g,'');
const field=(row,index)=>clean(row?.[index]);
const none=value=>!value||/^(?:-|--|N\/A|NA|NONE|NIL|0(?:\.0+)?)$/i.test(clean(value));
const same=(a,b)=>companyKey(a)===companyKey(b);
function unique(names){
 const seen=new Set();
 return names.filter(value=>{
  const key=companyKey(value);
  if(!key||seen.has(key))return false;
  seen.add(key);return true;
 });
}
function isActiveDirector(row,cessationCol){
 return none(field(row,cessationCol));
}
function directorsFrom(rows){
 const headerIndex=rows.findIndex(r=>/^director name$/i.test(field(r,0)));
 if(headerIndex<0)return [];
 const head=rows[headerIndex]||[];
 const cessationCol=head.findIndex(x=>/date of cessation/i.test(String(x??'')));
 if(cessationCol<0)return [];
 const names=[];
 for(const r of rows.slice(headerIndex+1)){
  const name=firstLine(field(r,0));
  if(!name||name.length>140||/^(?:director name|notes?|total|company name|date)$/i.test(name))continue;
  if(isActiveDirector(r,cessationCol))names.push(name);
 }
 return unique(names);
}
function membersFrom(rows){
 const names=[];
 for(let i=0;i<rows.length;i++){
  if(!/^name\s*:?\s*$/i.test(field(rows[i],0)))continue;
  const name=firstLine(field(rows[i],1));
  if(!name||name.length>140)continue;
  let ceased='',shares='';
  for(let j=i+1;j<Math.min(rows.length,i+25);j++){
   const r=rows[j];
   if(/^name\s*:?\s*$/i.test(field(r,0)))break;
   if(/date ceased to be a member/i.test(field(r,6)))ceased=field(r,7);
   if(/total shares held/i.test(field(r,6)))shares=field(r,7);
  }
  if(none(ceased)&&(!shares||(!none(shares)&&Number(shares.replace(/,/g,''))>0)))names.push(name);
 }
 return unique(names);
}
function beneficialOwnersFrom(rows){
 const headerIndex=rows.findIndex(r=>/^full name$/i.test(field(r,0)));
 if(headerIndex<0)return [];
 const names=[];
 for(const r of rows.slice(headerIndex+1)){
  const name=firstLine(field(r,0));
  if(!name||name.length>140||/^(?:notes?|total|full name|date)$/i.test(name))continue;
  const status=field(r,9);
  const ceased=/date\s+ceased\s*:\s*([^\r\n]*)/i.exec(status);
  if(ceased&&!none(ceased[1]))continue;
  names.push(name);
 }
 const seen=new Set();
 return names.filter(n=>{
  const k=companyKey(n);
  if(seen.has(k))return false;
  seen.add(k);return true;
 });
}
export function extractRegisterParticulars(sheets){
 const entries=Object.entries(sheets||{});
 const directorSheet=entries.find(([name])=>/^register of directors(?:\s|$)/i.test(name));
 const memberSheets=entries.filter(([name])=>/^register of members(?:\s|$)/i.test(name));
 const boSheet=entries.find(([name])=>/^register of (?:bo|beneficial owners)(?:\s|$)/i.test(name));
 if(!directorSheet||!memberSheets.length||!boSheet)
  throw Error('Register Book must contain Directors, Members and BO worksheets.');
 const directors=directorsFrom(directorSheet[1]);
 const members=unique(memberSheets.flatMap(([,rows])=>membersFrom(rows)));
 const beneficialOwners=beneficialOwnersFrom(boSheet[1]);
 return {directors,members,beneficialOwners};
}
/**
 * Keep exactly the original listing fields and the three current-person fields.
 * The removed labels are a known, limited set added by earlier register imports.
 * Names from a legacy combined field are separated before that field is discarded.
 */
export function compactRegisterColumns(model,{addMissing=true}={}){
 validateMasterListing(model);
 const legacyIndex=model.columns.findIndex(c=>normHeader(c.label)==='directors & members');
 const oldOwnersIndex=model.columns.findIndex(c=>normHeader(c.label)==='beneficial owners');
 const currentIndexes=REGISTER_PARTICULARS_COLUMNS.map(label=>
  model.columns.findIndex(c=>normHeader(c.label)===normHeader(label)));
 const keep=model.columns.map((col,i)=>({col,i}))
  .filter(({col})=>!REDUNDANT_REGISTER_HEADERS.has(normHeader(col.label)));
 const indexes=keep.map(x=>x.i);
 const copy={...model,columns:keep.map(({col})=>({...col})),
  rows:model.rows.map(row=>({...row,values:indexes.map(i=>row.values[i])}))};
 copy.nameColumn=indexes.indexOf(model.nameColumn);
 copy.registrationColumn=model.registrationColumn>=0?indexes.indexOf(model.registrationColumn):-1;
 if(copy.nameColumn<0||(model.registrationColumn>=0&&copy.registrationColumn<0))
  throw Error('Cannot remove an original company identification field.');
 const legacyCombined=legacyIndex>=0
  ?model.rows.map(row=>String(row.values[legacyIndex]||'')):[];
 const legacyOwners=oldOwnersIndex>=0
  ?model.rows.map(row=>String(row.values[oldOwnersIndex]||'')):[];
 const targets=REGISTER_PARTICULARS_COLUMNS.map((label,j)=>{
  let index=copy.columns.findIndex(c=>normHeader(c.label)===normHeader(label));
  if(index<0&&addMissing){
   index=copy.columns.length;
   copy.columns.push({id:'c'+index,label});
   for(const row of copy.rows)row.values.push('N/A');
  }
  return index;
 });
 copy.rows.forEach((row,i)=>{
  if(targets[0]>=0&&currentIndexes[0]<0&&legacyCombined[i]){
   const found=/^Directors:\s*([^\r\n]*)/im.exec(legacyCombined[i]);
   if(found&&found[1].trim())row.values[targets[0]]=found[1].trim();
  }
  if(targets[1]>=0&&currentIndexes[1]<0&&legacyCombined[i]){
   const found=/^Members:\s*([^\r\n]*)/im.exec(legacyCombined[i]);
   if(found&&found[1].trim())row.values[targets[1]]=found[1].trim();
  }
  if(targets[2]>=0&&currentIndexes[2]<0&&legacyOwners[i]&&legacyOwners[i]!=='N/A')
   row.values[targets[2]]=legacyOwners[i];
 });
 validateMasterListing(copy);
 return {model:copy,removed: model.columns.length-copy.columns.length};
}
function displayNames(values){
 return (values||[]).map(v=>String(v||'').replace(/\s+\(\d+(?:\.\d+)?%\)$/,'').trim())
  .filter(Boolean).filter((v,i,a)=>a.findIndex(x=>companyKey(x)===companyKey(v))===i).join('; ')||'N/A';
}
export function mergeRegisterParticulars(model,records,{replaceMissing=false}={}){
 validateMasterListing(model);
 const compacted=compactRegisterColumns(model);
 const copy=compacted.model;
 const cols=REGISTER_PARTICULARS_COLUMNS.map(label=>
  copy.columns.findIndex(c=>normHeader(c.label)===normHeader(label)));
 const sources=new Map();
 const duplicateKeys=new Set();
 for(const rec of records){
  const k=companyKey(rec.company);
  if(!k)continue;
  if(sources.has(k)){duplicateKeys.add(k);continue;}
  sources.set(k,rec);
 }
 let matchedRows=0;
 const missing=[];
 for(const row of copy.rows){
  const name=companyData(copy,row)?.name||'';
  const key=companyKey(name),rec=duplicateKeys.has(key)?null:sources.get(key);
  if(!rec){
   if(name)missing.push(name);
   if(replaceMissing)for(const col of cols)row.values[col]='N/A';
   continue;
  }
  const values=[displayNames(rec.directors),displayNames(rec.members),displayNames(rec.beneficialOwners)];
  if(values.some(v=>v.length>maxField))
   throw Error('Register Book names exceed the Master Listing cell length limit for '+name);
  cols.forEach((col,i)=>{row.values[col]=values[i];});
  matchedRows++;
 }
 validateMasterListing(copy);
 return {model:copy,matchedRows,missing,removed:compacted.removed};
}
/**
 * Preserve existing current-person fields when the user imports a fresh
 * master listing without them. Do not re-add previous combined or 42-column
 * statutory-detail columns. Never guess matches for duplicate company names.
 */
export function preserveRegisterParticulars(oldModel,nextModel){
 validateMasterListing(nextModel);
 const next=compactRegisterColumns(nextModel).model;
 if(!oldModel)return next;
 validateMasterListing(oldModel);
 const old=compactRegisterColumns(oldModel).model;
 const targets=REGISTER_PARTICULARS_COLUMNS.map(label=>
  next.columns.findIndex(c=>normHeader(c.label)===normHeader(label)));
 const origins=REGISTER_PARTICULARS_COLUMNS.map(label=>
  old.columns.findIndex(c=>normHeader(c.label)===normHeader(label)));
 const matches=new Map(),duplicates=new Set();
 for(const row of old.rows){
  const key=companyKey(companyData(old,row)?.name||'');
  if(!key)continue;
  if(matches.has(key)){duplicates.add(key);continue;}
  matches.set(key,row);
 }
 for(const row of next.rows){
  const key=companyKey(companyData(next,row)?.name||'');
  if(duplicates.has(key))continue;
  const orig=matches.get(key);
  if(!orig)continue;
  targets.forEach((to,i)=>{
   const from=origins[i];
   if(from<0)return;
   const current=String(row.values[to]??'').trim();
   const oldValue=String(orig.values[from]??'').trim();
   if((!current||current==='N/A')&&oldValue&&oldValue!=='N/A')
    row.values[to]=oldValue;
  });
 }
 return validateMasterListing(next);
}
export async function previewRegisterParticularsZip(file,model,{onProgress=()=>{}}={}){
 if(!model)throw Error('Import your Master Listing before syncing Register Books.');
 if(!file||!/\.zip$/i.test(file.name)||file.size===0||file.size>MAX_ZIP)
  throw Error('Choose a non-empty Register Book ZIP archive smaller than 80 MB.');
 onProgress('Reading Register Book archive locally…');
 const entries=unzipSync(new Uint8Array(await file.arrayBuffer()));
 const books=Object.entries(entries).filter(([p])=>/\.xlsx$/i.test(p)&&!/(?:^|\/)__MACOSX\//i.test(p));
 if(!books.length||books.length>500)throw Error('ZIP must contain 1 to 500 Excel Register Books.');
 if(books.reduce((n,[,bytes])=>n+bytes.byteLength,0)>MAX_UNPACKED)
  throw Error('Unpacked Register Books exceed the safe 120 MB limit.');
 const permitted=new Set(model.rows.map(r=>companyKey(companyData(model,r)?.name)).filter(Boolean));
 const records=[],unmatchedFiles=[],errors=[];
 for(let i=0;i<books.length;i++){
  const [path,bytes]=books[i];
  const basename=path.split(/[\\/]/).at(-1)||'';
  const company=basename.replace(/\.xlsx$/i,'').replace(/^register\s*book[_ -]*/i,'').trim();
  if(!permitted.has(companyKey(company))){unmatchedFiles.push(basename);continue;}
  if(!bytes.byteLength||bytes.byteLength>MAX_BOOK){errors.push(basename+': invalid workbook size');continue;}
  try{
   const bookFile={name:basename,size:bytes.byteLength,arrayBuffer:async()=>bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength)};
   const book=await openMasterListingWorkbook(bookFile);
   const required=book.sheetNames.filter(n=>/^master$|^register of directors(?:\s|$)|^register of members(?:\s|$)|^register of (?:bo|beneficial owners)(?:\s|$)/i.test(n));
   const sheets=Object.fromEntries(required.map(n=>[n,book.readSheet(n)]));
   const master=sheets.Master||[];
   const stated=master.find(r=>/^company name\s*:/i.test(field(r,0)));
   if(stated&&!same(field(stated,1),company))throw Error('Workbook company name differs from ZIP filename');
   records.push({company,...extractRegisterParticulars(sheets)});
  }catch(e){errors.push(basename+': '+(e.message||String(e)));}
  if(i%5===0||i===books.length-1)onProgress('Read '+(i+1)+' of '+books.length+' Register Books…');
 }
 const proposal=mergeRegisterParticulars(model,records);
 return {model:proposal.model,matchedRows:proposal.matchedRows,
  registerBooks:books.length,parsedBooks:records.length,missingCompanies:proposal.missing,
  unmatchedFiles,errors};
}
